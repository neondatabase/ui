/**
 * Pre-highlights every preview's demo source at build time.
 *
 * Scans demos/*-preview.tsx for their `?raw` source import, runs Shiki once
 * here in Node, and writes demos/generated/<preview>.ts exporting the
 * finished HTML. PreviewTabs renders that HTML directly, so pages ship
 * colored code in the static HTML — no client-side Shiki, no flash.
 *
 * Themes match Blume's code fences (github-light / github-dark). Colors are
 * inlined with light-dark(), so they follow the site's color-scheme with no
 * extra CSS. The root element is a <div>, not a <pre>, so Blume's global
 * `.prose pre` enhancer doesn't add a second copy button to it.
 *
 * Runs automatically before `dev` and `build` (see package.json). Re-run it
 * manually (or restart dev) after editing a demo source.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

import { codeToHtml } from "shiki";

const docsRoot = new URL("..", import.meta.url).pathname;
const demosDir = path.join(docsRoot, "demos");
const outDir = path.join(demosDir, "generated");

const RAW_IMPORT = /import\s+source\s+from\s+"(?<spec>[^"]+)\?raw"/u;

const previews = readdirSync(demosDir).filter((name) =>
  name.endsWith("-preview.tsx")
);

mkdirSync(outDir, { recursive: true });

const results = await Promise.all(
  previews.map(async (preview) => {
    const previewPath = path.join(demosDir, preview);
    const match = RAW_IMPORT.exec(readFileSync(previewPath, "utf-8"));

    if (!match?.groups) {
      return 0;
    }

    const sourcePath = path.resolve(demosDir, match.groups.spec);
    const source = readFileSync(sourcePath, "utf-8").trim();

    const html = await codeToHtml(source, {
      defaultColor: "light-dark()",
      lang: "tsx",
      themes: { dark: "github-dark", light: "github-light" },
      transformers: [
        {
          pre(node) {
            node.tagName = "div";
          },
        },
      ],
    });

    const base = preview.replace(/\.tsx$/u, "");
    const banner = `// Generated by scripts/build-highlighted.mjs from\n// ${path.relative(docsRoot, sourcePath)} — do not edit by hand.\n`;

    writeFileSync(
      path.join(outDir, `${base}.ts`),
      `${banner}export const highlightedHtml = ${JSON.stringify(html)};\n`
    );
    return 1;
  })
);

const count = results.reduce((sum, wrote) => sum + wrote, 0);
console.log(`build-highlighted: wrote ${count} modules to demos/generated`);
