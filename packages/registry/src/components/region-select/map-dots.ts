/** Decodes one hex row into per-column land flags. */
export const decodeRow = (hex: string): boolean[] => {
  const flags: boolean[] = [];

  for (const char of hex) {
    const nibble = Number.parseInt(char, 16).toString(2).padStart(4, "0");

    for (const bit of nibble) {
      flags.push(bit === "1");
    }
  }

  return flags;
};
